# Windows portable packaging smoke: compilerless .nova -> .exe and GUI target.
$ErrorActionPreference='Stop'
$root=Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Push-Location $root
try {
  $console=Join-Path $root 'bin\nova-native.exe'
  $gui=Join-Path $root 'bin\nova-windowed.exe'
  if (-not (Test-Path $console) -or -not (Test-Path $gui)) {throw 'Build both Windows runtimes first'}
  $tmp=Join-Path ([IO.Path]::GetTempPath()) ('Nova-Portable08-Łódź-'+[guid]::NewGuid().ToString('N'))
  [IO.Directory]::CreateDirectory($tmp)|Out-Null
  try {
    & (Join-Path $root 'nova.ps1') doctor
    if ($LASTEXITCODE -ne 0) { throw 'Nova doctor failed' }
    & (Join-Path $root 'nova.cmd') doctor
    if ($LASTEXITCODE -ne 0) { throw 'Nova.cmd doctor failed' }
    $src=Join-Path $root 'examples\bootstrap\trilingual.nova'
    $target=Join-Path $tmp 'Привіт-Żółw.exe'
    & (Join-Path $root 'nova.ps1') build -Source $src -Output $target
    if ($LASTEXITCODE -ne 0) {throw 'Portable build failed'}
    $expected = & $console run $src
    $actual = & $target
    if ($LASTEXITCODE -ne 0 -or ($expected -join "`n") -ne ($actual -join "`n")) {throw 'Portable EXE output mismatch'}
    $details=& $console inspect $target
    if ($LASTEXITCODE -ne 0 -or ($details -join "`n") -notmatch 'Integrity: OK') {throw 'Portable EXE integrity failed'}
    $recovered=Join-Path $tmp 'recovered.nbc'
    & $console unpack $target $recovered
    if ($LASTEXITCODE -ne 0) {throw 'Unpack failed'}
    $recompiled=Join-Path $tmp 'compiled.nbc'
    & $console exec (Join-Path $root 'compiler\novac_selfhost.nbc') --max-steps 15000000 -- $src $recompiled
    if ($LASTEXITCODE -ne 0) {throw 'Native Nova self-compiler failed'}
    $hashA=(Get-FileHash -LiteralPath $recovered -Algorithm SHA256).Hash
    $hashB=(Get-FileHash -LiteralPath $recompiled -Algorithm SHA256).Hash
    if ($hashA -ne $hashB) { throw 'Extracted bytecode differs from generated bytecode' }
    # For a windowed runner, verify packaging and native PE header; GUI interaction
    # is deliberately NOT automated on a headless CI agent.
    $guiTarget=Join-Path $tmp 'NovaWindowed.exe'
    & (Join-Path $root 'nova.ps1') build -Source $src -Output $guiTarget -Windowed
    if ($LASTEXITCODE -ne 0) {throw 'Windowed build failed'}
    $info=& $console inspect $guiTarget
    if ($LASTEXITCODE -ne 0 -or ($info -join "`n") -notmatch 'Windows PE x64') {throw 'Windowed EXE inspection failed'}
    Write-Output 'PASS: native Windows compilerless portable console and GUI packaging'
  } finally { Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue }
} finally { Pop-Location }
